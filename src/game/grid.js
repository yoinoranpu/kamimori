// 壁(土の札)の当たり判定に関する定数。
// 以前はゴールからのBFSで全体最適な経路を事前計算していたが、それだと敵が
// スタート地点の時点で壁の存在を「知っている」かのように最初から迂回してしまい
// 不自然だった。現在は engine.js 側で、壁に実際に近づいてから初めて迂回を
// 開始する局所的な回避ロジックに変更しているため、ここでは壁のサイズだけを定義する。
import { FIELD } from './constants.js'

const { cellSize } = FIELD

// 壁1個あたりが塞ぐ縦幅。フィールド全高(540px)を塞ごうとすると壁が大量に必要に
// なってしまうため、1〜2個の壁で現実的に迂回・集約を強制できるよう幅広に取る。
export const WALL_SPAN = 8
export const WALL_SPAN_PX = WALL_SPAN * cellSize
